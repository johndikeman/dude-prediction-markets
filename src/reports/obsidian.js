/**
 * ObsidianReporter - writes prediction market strategy reports
 * as markdown files into an Obsidian vault directory.
 */

import { writeFile, mkdir, readFile, access } from "node:fs/promises";
import { join } from "node:path";

export class ObsidianReporter {
  constructor(vaultPath = "/home/ubuntu/vault") {
    this.vaultPath = vaultPath;
    this.reportDir = join(vaultPath, "reports", "prediction-markets");
  }

  async ensureDirs() {
    await mkdir(this.reportDir, { recursive: true });
  }

  filenameFromDate(date = new Date()) {
    const iso = date.toISOString().slice(0, 19).replace(/[:T]/g, "-");
    return `prediction-market-report-${iso}.md`;
  }

  /**
   * Generate a markdown report string from run data.
   */
  generateMarkdown({ timestamp, strategies, snapshots, maintenanceActions, wallet, openrouter }) {
    const lines = [];
    lines.push(`# prediction market strategy report`);
    lines.push(`**generated:** ${timestamp}`);
    lines.push("");

    lines.push(`## strategies`);
    for (const s of strategies) {
      lines.push(`- **${s.name}** (\`${s.id}\`) — ${s.status}`);
      lines.push(`  - query: \`${s.query}\``);
      lines.push(`  - runs: ${s.runs ?? 0}`);
      lines.push(`  - last run: ${s.lastRun || "never"}`);
    }
    lines.push("");

    lines.push(`## data snapshots`);
    for (const snap of snapshots) {
      lines.push(`### ${snap.strategyId}`);
      lines.push(`- news items: ${snap.newsCount}`);
      lines.push(`- market items: ${snap.marketsCount}`);
      if (snap.signals.length) {
        lines.push(`- signals:`);
        for (const sig of snap.signals) {
          lines.push(`  - ${sig.type}: ${sig.message}`);
        }
      }
      lines.push("");
    }

    lines.push(`## maintenance actions`);
    if (maintenanceActions.length === 0) {
      lines.push("_no maintenance actions taken._");
    } else {
      for (const action of maintenanceActions) {
        lines.push(`- **${action.strategy}**: ${action.description}`);
        if (action.applied) {
          lines.push(`  - applied: yes`);
        }
      }
    }
    lines.push("");

    lines.push(`## wallet`);
    if (!wallet) {
      lines.push("_wallet tracking unavailable._");
    } else if (wallet.error || !wallet.address) {
      lines.push(`- error: ${wallet.error || "PM_WALLET_ADDRESS not configured"}`);
    } else {
      lines.push(`- address: \`${wallet.address}\``);
      lines.push(`- portfolio value: $${wallet.valueUsd ?? "?"}`);
      lines.push(`- native balance: ${wallet.nativeBalance ?? "?"} POL`);
      lines.push(`- open positions: ${wallet.positionCount ?? "?"}`);
      if (wallet.pnl?.changeUsd != null) {
        lines.push(
          `- pnl since first snapshot: $${wallet.pnl.changeUsd} (${wallet.pnl.changePct}%)`
        );
      }
      for (const e of wallet.errors ?? []) lines.push(`- warning: ${e}`);
    }
    lines.push("");

    lines.push(`## openrouter credits`);
    if (!openrouter || openrouter.error) {
      lines.push(`- error: ${openrouter?.error || "unknown"}`);
    } else {
      lines.push(`- remaining: $${openrouter.remaining.toFixed(2)}`);
      lines.push(`- total credits: $${openrouter.totalCredits.toFixed(2)}`);
      lines.push(`- recharge needed: ${openrouter.rechargeNeeded ? "yes" : "no"}`);
      lines.push(
        `- affordable recharge now: $${openrouter.affordableRechargeUsd.toFixed(2)} (portfolio value minus trading reserve)`
      );
    }
    lines.push("");

    lines.push(`## agent directives`);
    lines.push(
      "follow `src/prompts/cycle-instructions.md` in the dude-prediction-markets repo when acting on this report."
    );
    lines.push("");

    lines.push(`## notes`);
    lines.push("_this report is auto-generated by dude-prediction-markets._");
    return lines.join("\n");
  }

  /**
   * Write a report and return the absolute path.
   */
  async writeReport(data) {
    await this.ensureDirs();
    const filename = this.filenameFromDate();
    const filepath = join(this.reportDir, filename);
    const markdown = this.generateMarkdown(data);
    await writeFile(filepath, markdown, "utf-8");
    return filepath;
  }

  /**
   * Append a markdown link to the master task document.
   */
  async linkToTaskDoc(reportPath, taskDocPath = "betting market project.md") {
    const absoluteTaskDoc = join(this.vaultPath, taskDocPath);
    const relativeReport = reportPath.replace(this.vaultPath + "/", "");
    const linkLine = `- [[${relativeReport}|${new Date().toISOString().slice(0, 16)} report]]`;

    let content = "";
    try {
      await access(absoluteTaskDoc);
      content = await readFile(absoluteTaskDoc, "utf-8");
    } catch (err) {
      if (err.code !== "ENOENT") throw err;
    }

    if (!content.includes(linkLine)) {
      const updated = content + `\n${linkLine}\n`;
      await writeFile(absoluteTaskDoc, updated, "utf-8");
    }
  }
}
